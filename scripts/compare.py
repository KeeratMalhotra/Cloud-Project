"""Compare EdgePlus with EdgePlus-PEC (and the one-improvement ablations) on test days, with statistics.

Usage: python scripts/compare.py [--datasets citypulse airdelhi]

Reads runs/citypulse/<run>/eval_<dataset>_test.csv (learned policies, trained on CityPulse) and the greedy-EFT
reference in results/raw/heuristics_<dataset>_test_pec.csv. For each dataset and load it reports means with
bootstrap 95% CIs over episodes, and paired tests of EdgePlus-PEC against EdgePlus: episodes are paired by
(training seed, test seed), Wilcoxon signed-rank with Benjamini-Hochberg correction across all tests, and the
rank-biserial effect size. Writes results/summary/pec_comparison.json, results/summary/pec_comparison.md, and
figures docs/figures/pec_*.png.
"""
from __future__ import annotations

import argparse
import json
import os
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import wilcoxon

ROOT = Path(__file__).resolve().parents[1]
REGIMES = {50_000: "light", 100_000: "medium", 150_000: "stress"}
MAIN = {"EdgePlus": "edgeplus", "EdgePlus-PEC": "edgeplus_pec"}
ABL = {"+ priority queues": "edgeplus_pq", "+ energy-aware": "edgeplus_energy", "+ fast consensus": "edgeplus_cons"}
SEEDS = [0, 1, 2]
METRICS = ["success", "success_URLLC", "success_eMBB", "success_mMTC", "lat_p50", "lat_p95", "throughput",
           "cloud_share", "locality", "energy_total_j", "energy_it_j", "drive_energy_j", "km_driven",
           "dvfs_slowed", "ledger_commit_p50_s", "ledger_commit_p95_s", "ledger_final_p50_s", "ledger_final_p95_s",
           "ledger_cpu_share", "jain_site_success"]
TESTED = ["success", "success_URLLC", "lat_p95", "energy_total_j", "ledger_commit_p95_s", "ledger_final_p95_s"]


def load_runs(dataset: str, method: str, seeds: list[int]) -> pd.DataFrame:
    parts = []
    for s in seeds:
        p = ROOT / "runs" / "citypulse" / f"{method}_s{s}" / f"eval_{dataset}_test.csv"
        if p.exists():
            d = pd.read_csv(p)
            d["train_seed"] = s
            parts.append(d)
    return pd.concat(parts, ignore_index=True) if parts else pd.DataFrame()


def boot_ci(x: np.ndarray, reps: int = 5000, seed: int = 0) -> tuple[float, float]:
    x = np.asarray(x, float)
    x = x[np.isfinite(x)]
    if x.size < 2:
        return float("nan"), float("nan")
    rng = np.random.default_rng(seed)
    m = rng.choice(x, size=(reps, x.size)).mean(1)
    return float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def bh(p: list[float]) -> list[float]:
    p = np.asarray(p, float)
    n = len(p)
    order = np.argsort(p)
    q = np.empty(n)
    prev = 1.0
    for rank, i in reversed(list(enumerate(order, 1))):
        prev = min(prev, p[i] * n / rank)
        q[i] = prev
    return q.tolist()


def summarize(df: pd.DataFrame) -> dict:
    out = {"episodes": int(len(df))}
    for m in METRICS:
        if m in df.columns and df[m].notna().any():
            lo, hi = boot_ci(df[m].to_numpy())
            out[m] = {"mean": float(df[m].mean()), "ci95": [lo, hi]}
    return out


def paired(a: pd.DataFrame, b: pd.DataFrame, metric: str) -> dict | None:
    """b minus a, paired on (train_seed, seed)."""
    if metric not in a.columns or metric not in b.columns:
        return None
    m = a[["train_seed", "seed", metric]].merge(b[["train_seed", "seed", metric]], on=["train_seed", "seed"],
                                                 suffixes=("_a", "_b")).dropna()
    if len(m) < 2:
        return None
    d = (m[f"{metric}_b"] - m[f"{metric}_a"]).to_numpy()
    lo, hi = boot_ci(d)
    res = {"n": int(len(d)), "mean_diff": float(d.mean()), "ci95": [lo, hi]}
    if np.allclose(d, 0):
        res.update({"p": 1.0, "rank_biserial": 0.0})
        return res
    w = wilcoxon(d, zero_method="wilcox", alternative="two-sided")
    nz = d[d != 0]
    ranks = pd.Series(np.abs(nz)).rank().to_numpy()
    r_plus, r_minus = ranks[nz > 0].sum(), ranks[nz < 0].sum()
    res.update({"p": float(w.pvalue), "rank_biserial": float((r_plus - r_minus) / (r_plus + r_minus))})
    return res


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--datasets", nargs="+", default=["citypulse", "airdelhi"])
    args = ap.parse_args()
    result = {"methods": {**MAIN, **ABL}, "training_seeds": SEEDS, "datasets": {}}
    tests = []
    md = ["# EdgePlus vs EdgePlus-PEC on test days", "",
          "Learned policies trained on CityPulse training days (1.5M decisions each), evaluated frozen. "
          "Means over episodes with bootstrap 95% CIs. Generated by `scripts/compare.py`.", ""]
    for ds in args.datasets:
        rule = pd.DataFrame()
        rp = ROOT / "results" / "raw" / f"heuristics_{ds}_test_pec.csv"
        if rp.exists():
            rule = pd.read_csv(rp)
        dres = {}
        for n, regime in REGIMES.items():
            rows = {}
            frames = {}
            for label, meth in {**MAIN, **ABL}.items():
                seeds = SEEDS if label in MAIN else [0]
                d = load_runs(ds, meth, seeds)
                if d.empty:
                    continue
                d = d[d["n_tasks"] == n]
                if d.empty:
                    continue
                frames[label] = d
                rows[label] = summarize(d)
            for sysname, label in (("edgeplus", "greedy EFT (EdgePlus system)"),
                                   ("edgeplus_pec", "greedy EFT (PEC system)")):
                if not rule.empty:
                    g = rule[(rule["system"] == sysname) & (rule["n_tasks"] == n) & (rule["policy"] == "greedy_eft")]
                    if len(g):
                        rows[label] = summarize(g)
            if not rows:
                continue
            comp = {}
            if "EdgePlus" in frames and "EdgePlus-PEC" in frames:
                for m in METRICS:
                    r = paired(frames["EdgePlus"], frames["EdgePlus-PEC"], m)
                    if r is not None:
                        comp[m] = r
                        if m in TESTED and "p" in r:
                            tests.append((ds, regime, m))
            abl = {}
            if "EdgePlus" in frames:
                base0 = frames["EdgePlus"][frames["EdgePlus"]["train_seed"] == 0]
                for label in ABL:
                    if label in frames:
                        abl[label] = {m: paired(base0, frames[label], m) for m in TESTED}
            dres[regime] = {"summary": rows, "pec_minus_edgeplus": comp, "ablations_minus_edgeplus_s0": abl}
        result["datasets"][ds] = dres
    # Benjamini-Hochberg across the main paired tests
    ps = [result["datasets"][d][r]["pec_minus_edgeplus"][m]["p"] for d, r, m in tests]
    for (d, r, m), q in zip(tests, bh(ps) if ps else []):
        result["datasets"][d][r]["pec_minus_edgeplus"][m]["q_bh"] = q
    out = ROOT / "results" / "summary" / "pec_comparison.json"
    out.write_text(json.dumps(result, indent=2))

    def fmt(s: dict, m: str, pct: bool) -> str:
        if m not in s:
            return "–"
        v, (lo, hi) = s[m]["mean"], s[m]["ci95"]
        if pct:
            return f"{100 * v:.1f} [{100 * lo:.1f}, {100 * hi:.1f}]" if np.isfinite(lo) else f"{100 * v:.1f}"
        if m.startswith("energy") or m.startswith("drive"):
            return f"{v / 1e6:.2f} MJ" if v > 1e5 else f"{v / 1e3:.1f} kJ"
        return f"{v:.2f}" if np.isfinite(v) else "–"

    for ds, dres in result["datasets"].items():
        for regime, block in dres.items():
            md += [f"## {ds}, {regime} load", "",
                   "| Method | Episodes | Success % | URLLC % | Lp95 (s) | Cloud % | Energy | Commit p95 (s) | Finality p95 (s) |",
                   "|---|---|---|---|---|---|---|---|---|"]
            for label, s in block["summary"].items():
                md.append(f"| {label} | {s['episodes']} | {fmt(s, 'success', True)} | {fmt(s, 'success_URLLC', True)} | "
                          f"{fmt(s, 'lat_p95', False)} | {fmt(s, 'cloud_share', True)} | {fmt(s, 'energy_total_j', False)} | "
                          f"{fmt(s, 'ledger_commit_p95_s', False)} | {fmt(s, 'ledger_final_p95_s', False)} |")
            c = block["pec_minus_edgeplus"]
            if c:
                md += ["", "EdgePlus-PEC minus EdgePlus (paired, n = %d):" % c["success"]["n"], ""]
                for m in TESTED:
                    if m in c:
                        r = c[m]
                        scale = 100 if m.startswith("success") else 1
                        unit = " pp" if scale == 100 else ""
                        md.append(f"- {m}: {scale * r['mean_diff']:+.3g}{unit} (95% CI {scale * r['ci95'][0]:+.3g} to "
                                  f"{scale * r['ci95'][1]:+.3g}), Wilcoxon p = {r.get('p', float('nan')):.2g}, "
                                  f"BH q = {r.get('q_bh', float('nan')):.2g}, rank-biserial r = {r.get('rank_biserial', float('nan')):+.2f}")
            md.append("")
    (ROOT / "results" / "summary" / "pec_comparison.md").write_text("\n".join(md))
    print("\n".join(md))
    figures(result)


def figures(result: dict) -> None:
    os.environ.setdefault("MPLCONFIGDIR", str(ROOT / ".cache" / "matplotlib"))
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig_dir = ROOT / "docs" / "figures"
    labels = ["greedy EFT (EdgePlus system)", "EdgePlus", "+ priority queues", "+ energy-aware", "+ fast consensus",
              "EdgePlus-PEC", "greedy EFT (PEC system)"]
    for metric, ylabel, fname, scale in (("success", "On-time success (%)", "pec_success", 100),
                                         ("success_URLLC", "URLLC on-time success (%)", "pec_urllc", 100),
                                         ("energy_total_j", "Total energy per episode (MJ)", "pec_energy", 1e-6)):
        dsets = list(result["datasets"])
        fig, axes = plt.subplots(1, len(dsets), figsize=(5.2 * len(dsets), 3.6), squeeze=False)
        for ax, ds in zip(axes[0], dsets):
            block = result["datasets"][ds].get("stress")
            if not block:
                continue
            xs, ys, es, cols = [], [], [], []
            for lab in labels:
                s = block["summary"].get(lab)
                if not s or metric not in s:
                    continue
                v, (lo, hi) = s[metric]["mean"], s[metric]["ci95"]
                xs.append(lab.replace(" (", "\n("))
                ys.append(v * scale)
                es.append([(v - lo) * scale if np.isfinite(lo) else 0, (hi - v) * scale if np.isfinite(hi) else 0])
                cols.append("#888888" if lab.startswith("greedy") else ("#d62728" if lab == "EdgePlus-PEC" else
                                                                        ("#1f77b4" if lab == "EdgePlus" else "#9ecae1")))
            ax.bar(range(len(xs)), ys, yerr=np.array(es).T if es else None, color=cols, capsize=3)
            ax.set_xticks(range(len(xs)))
            ax.set_xticklabels(xs, rotation=35, ha="right", fontsize=7)
            ax.set_title(f"{ds}, 150k tasks", fontsize=9)
            ax.set_ylabel(ylabel, fontsize=8)
            ax.grid(axis="y", alpha=0.3)
        fig.tight_layout()
        fig.savefig(fig_dir / f"{fname}.png", dpi=150)
        plt.close(fig)


if __name__ == "__main__":
    main()
